package org.apache.camel.dataformat.deflater.springboot;

import org.apache.camel.spring.boot.DataFormatConfigurationPropertiesCommon;
import org.springframework.boot.context.properties.ConfigurationProperties;

/**
 * Compress and decompress messages using java.util.zip.GZIP*Stream
 * 
 * Generated by camel-package-maven-plugin - do not edit this file!
 */
@ConfigurationProperties(prefix = "camel.dataformat.gzip-deflater")
public class GzipDeflaterDataFormatConfiguration
        extends
            DataFormatConfigurationPropertiesCommon {

    /**
     * Whether to enable auto configuration of the gzipDeflater data format.
     * This is enabled by default.
     */
    private Boolean enabled;
    /**
     * Set the maximum decompressed size of the data (in bytes). The default
     * value if not specified corresponds to 1 gigabyte. An IOException is
     * thrown if the decompressed size exceeds this amount. Set to -1 to disable
     * setting a maximum decompressed size.
     */
    private Long maxDecompressedSize = 1073741824L;

    public Long getMaxDecompressedSize() {
        return maxDecompressedSize;
    }

    public void setMaxDecompressedSize(Long maxDecompressedSize) {
        this.maxDecompressedSize = maxDecompressedSize;
    }
}