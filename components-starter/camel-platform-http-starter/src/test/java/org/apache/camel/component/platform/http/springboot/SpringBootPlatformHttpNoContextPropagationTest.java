package org.apache.camel.component.platform.http.springboot;

import io.restassured.RestAssured;
import org.apache.camel.spring.boot.CamelAutoConfiguration;
import org.apache.camel.test.spring.junit6.CamelSpringBootTest;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.autoconfigure.EnableAutoConfiguration;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.core.env.Environment;

import static io.restassured.RestAssured.given;
import static org.hamcrest.Matchers.equalTo;
import static org.hamcrest.Matchers.startsWith;

/**
 * Without spring.task.execution.propagate-context, the executor thread that runs the route does not get the context of
 * the request: context propagation stays opt-in, as for Spring Boot's own task executors. The same route as
 * {@link SpringBootPlatformHttpContextPropagationTest}, which sets the property.
 */
@EnableAutoConfiguration
@CamelSpringBootTest
@SpringBootTest(webEnvironment = SpringBootTest.WebEnvironment.RANDOM_PORT, classes = { CamelAutoConfiguration.class,
        SpringBootPlatformHttpNoContextPropagationTest.class,
        SpringBootPlatformHttpContextPropagationTest.TestConfiguration.class,
        PlatformHttpComponentAutoConfiguration.class, SpringBootPlatformHttpAutoConfiguration.class })
public class SpringBootPlatformHttpNoContextPropagationTest {

    @Autowired
    private Environment env;

    @BeforeEach
    void setUp() {
        RestAssured.port = env.getRequiredProperty("local.server.port", Integer.class);
    }

    @Test
    void routeDoesNotSeeTheObservationOfTheRequestByDefault() {
        given()
                .get("/observed")
                .then()
                .statusCode(200)
                .header("RouteThread", startsWith("task-"))
                .body(equalTo("no observation of the request"));
    }
}
