package org.apache.camel.dataformat.toon.springboot;

import org.apache.camel.spring.boot.DataFormatConfigurationPropertiesCommon;
import org.springframework.boot.context.properties.ConfigurationProperties;

/**
 * Marshal JSON-compatible Java values to TOON (Token-Oriented Object Notation)
 * and unmarshal TOON back to Java objects.
 * 
 * Generated by camel-package-maven-plugin - do not edit this file!
 */
@ConfigurationProperties(prefix = "camel.dataformat.toon")
public class ToonDataFormatConfiguration
        extends
            DataFormatConfigurationPropertiesCommon {

    /**
     * Whether to enable auto configuration of the toon data format. This is
     * enabled by default.
     */
    private Boolean enabled;
    /**
     * Number of spaces per indentation level.
     */
    private Integer indent = 2;
    /**
     * Delimiter used for tabular array rows and inline primitive arrays.
     */
    private String delimiter = "COMMA";
    /**
     * Whether to prefix array lengths with a hash marker so arrays render as
     * hash-prefixed lengths instead of plain lengths.
     */
    private Boolean lengthMarker = false;
    /**
     * Whether to enable strict validation when unmarshalling TOON. When false,
     * JToon uses best-effort parsing.
     */
    private Boolean strict = true;
    /**
     * Whether the data format should set the Content-Type header to text/toon
     * when marshalling.
     */
    private Boolean contentTypeHeader = true;

    public Integer getIndent() {
        return indent;
    }

    public void setIndent(Integer indent) {
        this.indent = indent;
    }

    public String getDelimiter() {
        return delimiter;
    }

    public void setDelimiter(String delimiter) {
        this.delimiter = delimiter;
    }

    public Boolean getLengthMarker() {
        return lengthMarker;
    }

    public void setLengthMarker(Boolean lengthMarker) {
        this.lengthMarker = lengthMarker;
    }

    public Boolean getStrict() {
        return strict;
    }

    public void setStrict(Boolean strict) {
        this.strict = strict;
    }

    public Boolean getContentTypeHeader() {
        return contentTypeHeader;
    }

    public void setContentTypeHeader(Boolean contentTypeHeader) {
        this.contentTypeHeader = contentTypeHeader;
    }
}